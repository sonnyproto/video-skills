"""Build the film from film.json: mix the sound and write index.html.

    python3 tools/build.py

The story (footage, narration lines, captions) lives in film.json; change that, not this file. Each line is one
narration file placed at `at` seconds; each caption is [text, seconds after the line starts] and holds until the next
caption or the next line. The mix is the generated clips' own sound at `audio.bed_volume` under the narration,
normalised to -14 LUFS with true peak under -1.5 dBTP. Needs ffmpeg.
"""
import html
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
F = json.loads((ROOT / "film.json").read_text())
W, H = F["size"]
L = F["audio"]["length"]

# 1. sound: clip audio as a bed, narration lines on top
ins, filt = [], []
for i, c in enumerate(F["footage"]):
    ins += ["-i", c["src"]]
bed = "".join(f"[{i}:a]" for i in range(len(F["footage"])))
filt.append(f"{bed}concat=n={len(F['footage'])}:v=0:a=1,volume={F['audio']['bed_volume']},apad[bed]")
n0 = len(F["footage"])
for j, ln in enumerate(F["lines"]):
    ins += ["-i", ln["vo"]]
    ms = int(round(ln["at"] * 1000))
    filt.append(f"[{n0 + j}:a]adelay={ms}:all=1[v{j}]")
vo = "".join(f"[v{j}]" for j in range(len(F["lines"])))
filt.append(f"{vo}amix=inputs={len(F['lines'])}:normalize=0[vo]")
fo = F["audio"]["fade_out"]
filt.append(f"[bed][vo]amix=inputs=2:normalize=0:duration=longest,loudnorm=I=-14:TP=-1.5:LRA=11,"
            f"afade=t=out:st={L - fo:.2f}:d={fo}[m]")
subprocess.run(["ffmpeg", "-loglevel", "error", "-y", *ins, "-filter_complex", ";".join(filt), "-map", "[m]",
                "-t", str(L), "-ar", "48000", "assets/audio/mix.mp3"], cwd=ROOT, check=True)

# 2. picture: footage clips, one caption track, the mix
s = F["caption_style"]
vids = "\n".join(
    f'  <video id="shot{i + 1}" class="clip" data-start="{c["start"]}" data-duration="{min(c["length"], L - c["start"]):.3f}" '
    f'data-track-index="1" src="{c["src"]}" muted playsinline></video>' for i, c in enumerate(F["footage"]))
caps, k = [], 0
for j, ln in enumerate(F["lines"]):
    nxt = F["lines"][j + 1]["at"] if j + 1 < len(F["lines"]) else L
    for m, (text, off) in enumerate(ln["captions"]):
        st = ln["at"] + off
        en = ln["at"] + ln["captions"][m + 1][1] if m + 1 < len(ln["captions"]) else nxt
        k += 1
        caps.append(f'  <div id="cap{k}" class="clip sub" data-start="{st:.2f}" data-duration="{en - st:.2f}" '
                    f'data-track-index="2"><span>{html.escape(text)}</span></div>')

(ROOT / "index.html").write_text(f"""<!doctype html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width={W}, height={H}" />
<!-- generated by tools/build.py from film.json -->
<script src="https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js"></script>
<style>
* {{ margin: 0; padding: 0; box-sizing: border-box; }}
html, body {{ width: {W}px; height: {H}px; overflow: hidden; background: #120c1c; }}
#root {{ position: relative; width: 100%; height: 100%; }}
video {{ position: absolute; inset: 0; width: {W}px; height: {H}px; object-fit: cover; }}
.sub {{ position: absolute; left: {s["side"]}px; right: {s["side"]}px; bottom: {s["bottom"]}px; text-align: center; }}
.sub span {{ display: inline-block; font: {s["weight"]} {s["size"]}px/1.3 "{s["font"]}", sans-serif; color: {s["text"]};
  padding: 8px 18px; border-radius: 12px; background: {s["box"]}; }}
</style>
</head>
<body>
<div id="root" data-composition-id="main" data-start="0" data-duration="{L}" data-width="{W}" data-height="{H}">
{vids}
{chr(10).join(caps)}
  <audio id="mix" class="clip" data-start="0" data-duration="{L}" data-track-index="10" src="assets/audio/mix.mp3" data-volume="1"></audio>
</div>
<script>
window.__timelines = window.__timelines || {{}};
const tl = gsap.timeline({{ paused: true }});
document.querySelectorAll(".sub span").forEach(s => {{
  tl.fromTo(s, {{ opacity: 0, y: 10 }}, {{ opacity: 1, y: 0, duration: 0.25, ease: "power2.out" }}, parseFloat(s.parentElement.dataset.start));
}});
tl.set({{}}, {{}}, {L});
window.__timelines["main"] = tl;
</script>
</body>
</html>
""")
print("wrote index.html and assets/audio/mix.mp3")
